#!/usr/bin/env bash
# PreToolUse hook: stop Claude from changing the schema any way but `WattWise.Cli migrate`
# (no `dotnet ef database update`) and from hand-editing the files `dotnet ef` generates
# (migration designers and the model snapshot). Migration bodies stay editable.
# Exit 2 shows stderr to Claude.
set -euo pipefail

input=$(cat)
tool=$(jq -r '.tool_name // empty' <<<"$input")

case "$tool" in
  Bash)
    command=$(jq -r '.tool_input.command // empty' <<<"$input")
    if [[ "$command" =~ dotnet[-\ ]ef[[:space:]]+database[[:space:]]+update ]]; then
      echo 'Only `WattWise.Cli migrate` changes the schema; see docs/development.md#migrations.' >&2
      exit 2
    fi
    ;;
  Edit | Write | MultiEdit)
    file=$(jq -r '.tool_input.file_path // empty' <<<"$input")
    if [[ "$file" == */backend/src/WattWise.Infrastructure/Persistence/Migrations/* ]] &&
      [[ "$file" == *.Designer.cs || "$(basename "$file")" == AppDbContextModelSnapshot.cs ]]; then
      echo 'Generated by dotnet ef; change the model and regenerate (/ef-migration).' >&2
      exit 2
    fi
    ;;
esac
exit 0
