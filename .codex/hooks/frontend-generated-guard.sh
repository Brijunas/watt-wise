#!/usr/bin/env bash
# PreToolUse hook: stop Claude from hand-editing the generated API client.
# Exit 2 shows stderr to Claude.
set -euo pipefail

file=$(jq -r '.tool_input.file_path // empty')

if [[ "$file" == */packages/api-client/src/generated/* ]]; then
  echo 'Generated by `pnpm generate:api` from the Api'"'"'s OpenAPI document; change the endpoint and regenerate (frontend/docs/architecture.md#api-client).' >&2
  exit 2
fi
exit 0
